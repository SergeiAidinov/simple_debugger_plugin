package target_debug;

public class Tourist {
	
	private final String name;
	private final String surname;
	
	public Tourist(String name, String surname) {
		super();
		this.name = name;
		this.surname = surname;
	}

	public String getName() {
		return name;
	}

	public String getSurname() {
		return surname;
	}
	
}
